function buildExcel() {
  const wb = XLSX.utils.book_new();
  const rows = [HEADER_ROW];

  for (const item of DIALOGUES_DATA) {
    const row = [item.desc];
    for (let i = 0; i < 6; i++) {
      row.push(item.lines[i] || '');
    }
    rows.push(row);
  }

  const ws = XLSX.utils.aoa_to_sheet(rows);

  ws['!cols'] = [
    { wch: 60 },
    { wch: 40 },
    { wch: 40 },
    { wch: 40 },
    { wch: 40 },
    { wch: 40 },
    { wch: 40 },
  ];

  XLSX.utils.book_append_sheet(wb, ws, '角色对话');

  const outputPath = path.join(__dirname, 'dialogues.xlsx');
  XLSX.writeFile(wb, outputPath);
  console.log(`✅ 生成成功: ${outputPath}`);

  console.log('ℹ️  assets/dialogues.xlsx 是指向本文件的软链接，无需单独同步。');
}

buildExcel();
